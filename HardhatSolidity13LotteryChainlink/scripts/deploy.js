const { ethers, network, artifacts } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log("=== Deploy Lottery Chainlink VRF ===");
  console.log("Deployer account :", deployer.address);
  console.log("Network          :", network.name);

  // 1. Deploy Mock VRF Coordinator (per test locali)
  const baseFee = ethers.parseEther("0.25"); // 0.25 LINK
  const gasPriceLink = 1e9; // 1 gwei

  const VRFCoordinatorV2Mock = await ethers.getContractFactory("VRFCoordinatorV2Mock");
  const vrfCoordinator = await VRFCoordinatorV2Mock.deploy(baseFee, gasPriceLink);
  await vrfCoordinator.waitForDeployment();
  const vrfAddress = await vrfCoordinator.getAddress();
  console.log("✅ VRFCoordinatorV2Mock deployed to:", vrfAddress);

  // 2. Crea e finanzia la Subscription VRF
  const txSub = await vrfCoordinator.createSubscription();
  await txSub.wait();
  const subId = 1n; // Il mock parte sempre da id 1
  await (await vrfCoordinator.fundSubscription(subId, ethers.parseEther("10"))).wait();
  console.log(`✅ VRF Subscription #${subId} creata e finanziata con 10 LINK mock`);

  // 3. Deploy NAO Token
  const MockERC20 = await ethers.getContractFactory("NAOTOKENERC20");
  const naoToken = await MockERC20.deploy("NAO Token", "NAO");
  await naoToken.waitForDeployment();
  const tokenAddress = await naoToken.getAddress();
  console.log("✅ NAO Token deployed to           :", tokenAddress);

  // 4. Deploy Lottery
  // Costo biglietto: 1 NAO
  const entryFee = ethers.parseEther("1");
  const keyHash = "0xd89b2bf150e3b9e13446986e571fb9cab24b13cea0a43ea20a6049a85cc807cc";

  const Lottery = await ethers.getContractFactory("Lottery");
  const lottery = await Lottery.deploy(
    subId,
    vrfAddress,
    keyHash,
    entryFee,
    tokenAddress
  );
  await lottery.waitForDeployment();
  const lotteryAddress = await lottery.getAddress();
  console.log("✅ Lottery deployed to             :", lotteryAddress);

  // 5. Aggiungi Lottery come consumer autorizzato alla subscription VRF
  await (await vrfCoordinator.addConsumer(subId, lotteryAddress)).wait();
  console.log("✅ Lottery aggiunta come consumer alla VRF subscription");

  // 6. Salva indirizzi e info su deployed-contract.json
  const { chainId } = await ethers.provider.getNetwork();
  const deployment = {
    network: network.name,
    chainId: chainId.toString(),
    deployer: deployer.address,
    token: tokenAddress,
    vrfCoordinator: vrfAddress,
    lottery: lotteryAddress,
    subscriptionId: subId.toString(),
    keyHash: keyHash,
    entryFee: entryFee.toString(),
    deployedAt: new Date().toISOString()
  };

  const deployFile = path.join(__dirname, "..", "deployed-contract.json");
  fs.writeFileSync(deployFile, JSON.stringify(deployment, null, 2));
  console.log("📄 Informazioni salvate in deployed-contract.json");

  // 7. Esporta file di configurazione e ABI per il client frontend
  const clientContractsDir = path.join(__dirname, "..", "client", "src", "contracts");
  fs.mkdirSync(clientContractsDir, { recursive: true });

  const configContent = `// Autogenerated by scripts/deploy.js — non modificare manualmente
export const TOKEN_ADDRESS = "${tokenAddress}";
export const VRF_COORDINATOR_ADDRESS = "${vrfAddress}";
export const LOTTERY_ADDRESS = "${lotteryAddress}";
export const SUBSCRIPTION_ID = "${subId.toString()}";
export const KEY_HASH = "${keyHash}";
export const ENTRY_FEE = "${entryFee.toString()}";
export const CHAIN_ID = "${chainId}";
`;
  fs.writeFileSync(path.join(clientContractsDir, "config.js"), configContent);

  const tokenArtifact = await artifacts.readArtifact("NAOTOKENERC20");
  fs.writeFileSync(
    path.join(clientContractsDir, "token_abi.json"),
    JSON.stringify(tokenArtifact.abi, null, 2)
  );

  const lotteryArtifact = await artifacts.readArtifact("Lottery");
  fs.writeFileSync(
    path.join(clientContractsDir, "lottery_abi.json"),
    JSON.stringify(lotteryArtifact.abi, null, 2)
  );

  const vrfArtifact = await artifacts.readArtifact("VRFCoordinatorV2Mock");
  fs.writeFileSync(
    path.join(clientContractsDir, "vrf_abi.json"),
    JSON.stringify(vrfArtifact.abi, null, 2)
  );

  console.log("📦 Indirizzi e ABI esportati in client/src/contracts/");
  console.log("=== Deployment completato con successo ===\n");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
