const { ethers, network, artifacts } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log("Deploying contracts with the account:", deployer.address);

  // 1. Deploy Governance Token
  const GovernanceToken = await ethers.getContractFactory("GovernanceToken");
  const token = await GovernanceToken.deploy();
  await token.waitForDeployment();
  const tokenAddress = await token.getAddress();
  console.log("GovernanceToken deployed to:", tokenAddress);

  // Delegate votes to self to activate them
  await token.delegate(deployer.address);
  console.log("Delegated votes to deployer");

  // 2. Deploy Timelock
  // Min delay 0 for testing/simulation (in production: e.g. 2 days = 172800)
  const minDelay = 0; 
  const TimeLock = await ethers.getContractFactory("TimeLock");
  const timelock = await TimeLock.deploy(minDelay, [], [], deployer.address);
  await timelock.waitForDeployment();
  const timelockAddress = await timelock.getAddress();
  console.log("TimeLock deployed to:", timelockAddress);

  // 3. Deploy Governor
  const MyGovernor = await ethers.getContractFactory("MyGovernor");
  const governor = await MyGovernor.deploy(tokenAddress, timelockAddress);
  await governor.waitForDeployment();
  const governorAddress = await governor.getAddress();
  console.log("Governor deployed to:", governorAddress);

  // 4. Setup Roles
  // Timelock roles: Proposer & Canceller = Governor, Executor = Anyone (address(0))
  const proposerRole = await timelock.PROPOSER_ROLE();
  const cancellerRole = await timelock.CANCELLER_ROLE();
  const executorRole = await timelock.EXECUTOR_ROLE();
  const adminRole = await timelock.DEFAULT_ADMIN_ROLE();

  await timelock.grantRole(proposerRole, governorAddress);
  await timelock.grantRole(cancellerRole, governorAddress);
  await timelock.grantRole(executorRole, ethers.ZeroAddress);
  await timelock.revokeRole(adminRole, deployer.address); // Revoke admin from deployer
  console.log("Timelock roles setup complete (Proposer, Canceller, Executor)");

  // 5. Deploy Target Contract (Box)
  const Box = await ethers.getContractFactory("Box");
  const box = await Box.deploy();
  await box.waitForDeployment();
  const boxAddress = await box.getAddress();
  console.log("Box deployed to:", boxAddress);

  // Transfer ownership of Box to Timelock
  await box.transferOwnership(timelockAddress);
  console.log("Box ownership transferred to Timelock");

  // 6. Save deployment info to deployed-contract.json
  const { chainId } = await ethers.provider.getNetwork();
  const deployment = {
    network: network.name,
    chainId: chainId.toString(),
    deployer: deployer.address,
    token: tokenAddress,
    timelock: timelockAddress,
    governor: governorAddress,
    box: boxAddress,
    deployedAt: new Date().toISOString()
  };
  const file = path.join(__dirname, "..", "deployed-contract.json");
  fs.writeFileSync(file, JSON.stringify(deployment, null, 2));
  console.log("Deployment info saved to deployed-contract.json");

  // 7. Export configuration and ABIs to frontend client
  const clientContractsDir = path.join(__dirname, "..", "client", "src", "contracts");
  fs.mkdirSync(clientContractsDir, { recursive: true });

  const configContent = `// Autogenerated by scripts/deploy.js
export const TOKEN_ADDRESS = "${tokenAddress}";
export const TIMELOCK_ADDRESS = "${timelockAddress}";
export const GOVERNOR_ADDRESS = "${governorAddress}";
export const BOX_ADDRESS = "${boxAddress}";
export const CHAIN_ID = "${chainId}";
`;
  fs.writeFileSync(path.join(clientContractsDir, "config.js"), configContent);

  const tokenArtifact = await artifacts.readArtifact("GovernanceToken");
  fs.writeFileSync(path.join(clientContractsDir, "token_abi.json"), JSON.stringify(tokenArtifact.abi, null, 2));

  const timelockArtifact = await artifacts.readArtifact("TimeLock");
  fs.writeFileSync(path.join(clientContractsDir, "timelock_abi.json"), JSON.stringify(timelockArtifact.abi, null, 2));

  const governorArtifact = await artifacts.readArtifact("MyGovernor");
  fs.writeFileSync(path.join(clientContractsDir, "governor_abi.json"), JSON.stringify(governorArtifact.abi, null, 2));

  const boxArtifact = await artifacts.readArtifact("Box");
  fs.writeFileSync(path.join(clientContractsDir, "box_abi.json"), JSON.stringify(boxArtifact.abi, null, 2));

  console.log("Exported contract addresses & ABIs to client/src/contracts/");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
