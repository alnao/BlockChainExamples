const { ethers, network, artifacts } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log("Deploying contracts with the account:", deployer.address);

  // 1. Deploy NAO Token (fix: factory name deve corrispondere al nome del contratto Solidity)
  const MockERC20 = await ethers.getContractFactory("NAOTOKENERC20");
  const naoToken = await MockERC20.deploy("NAO Token", "NAO");
  await naoToken.waitForDeployment();
  const tokenAddress = await naoToken.getAddress();
  console.log("NAO Token deployed to:", tokenAddress);

  // 2. Deploy NFT Collection
  //    publicMintPrice = 0.01 ETH, maxSupply = 0 (illimitata)
  const NFTCollection = await ethers.getContractFactory("NFTCollection");
  const nft = await NFTCollection.deploy(ethers.parseEther("0.01"), 0);
  await nft.waitForDeployment();
  const nftAddress = await nft.getAddress();
  console.log("NFTCollection deployed to:", nftAddress);

  // 3. Deploy Marketplace con fee 2.5% (250 basis points)
  const Marketplace = await ethers.getContractFactory("Marketplace");
  const marketplace = await Marketplace.deploy(tokenAddress, 250);
  await marketplace.waitForDeployment();
  const marketplaceAddress = await marketplace.getAddress();
  console.log("Marketplace deployed to:", marketplaceAddress);

  // 4. Mint un NFT di esempio al deployer
  await (await nft.mint(deployer.address, "ipfs://example-metadata/0")).wait();
  console.log("Minted NFT #0 to deployer");

  // 5. Salva gli indirizzi in deployed-contract.json
  const { chainId } = await ethers.provider.getNetwork();
  const deployment = {
    network: network.name,
    chainId: chainId.toString(),
    deployer: deployer.address,
    token: tokenAddress,
    nftCollection: nftAddress,
    marketplace: marketplaceAddress,
    deployedAt: new Date().toISOString()
  };
  const deployFile = path.join(__dirname, "..", "deployed-contract.json");
  fs.writeFileSync(deployFile, JSON.stringify(deployment, null, 2));
  console.log("Deployment info saved to deployed-contract.json");

  // 6. Esporta configurazione e ABI nel frontend client
  const clientContractsDir = path.join(__dirname, "..", "client", "src", "contracts");
  fs.mkdirSync(clientContractsDir, { recursive: true });

  const configContent = `// Autogenerated by scripts/deploy.js — non modificare manualmente
export const TOKEN_ADDRESS = "${tokenAddress}";
export const NFT_ADDRESS = "${nftAddress}";
export const MARKETPLACE_ADDRESS = "${marketplaceAddress}";
export const CHAIN_ID = "${chainId}";
`;
  fs.writeFileSync(path.join(clientContractsDir, "config.js"), configContent);

  const tokenArtifact = await artifacts.readArtifact("NAOTOKENERC20");
  fs.writeFileSync(
    path.join(clientContractsDir, "token_abi.json"),
    JSON.stringify(tokenArtifact.abi, null, 2)
  );

  const nftArtifact = await artifacts.readArtifact("NFTCollection");
  fs.writeFileSync(
    path.join(clientContractsDir, "nft_abi.json"),
    JSON.stringify(nftArtifact.abi, null, 2)
  );

  const marketplaceArtifact = await artifacts.readArtifact("Marketplace");
  fs.writeFileSync(
    path.join(clientContractsDir, "marketplace_abi.json"),
    JSON.stringify(marketplaceArtifact.abi, null, 2)
  );

  console.log("Exported contract addresses & ABIs to client/src/contracts/");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
